/**
 * ทำให้คำค้นของผู้ใช้เป็น "ตัวอักษรธรรมดา" ก่อนเอาไปต่อเป็นรูปแบบของ ILIKE (ตรวจรอบ 18)
 *
 * ใน LIKE/ILIKE เครื่องหมาย % แปลว่า "อะไรก็ได้กี่ตัวก็ได้" และ _ แปลว่า "อักขระใดก็ได้หนึ่งตัว"
 * คำค้นถูกเอาไปวางเป็น `%${q}%` ตรง ๆ — พิมพ์ % ลงช่องค้นหาจึงกลายเป็น `%%%`
 * ซึ่งแปลว่า "เอาทั้งหมด" ระบบคืนทั้งตารางแทนที่จะบอกว่าไม่พบ (พิสูจน์แล้ว: customers 4/4 · patients 4/4)
 * บนฐานจริงที่มีข้อมูลเยอะ นอกจากผลลัพธ์ผิดแล้วยังเป็นคำสั่งที่กวาดทั้งตารางทุกครั้งที่กด
 *
 * \\ ต้องหนีก่อนตัวอื่นเสมอ ไม่งั้นแบ็กสแลชที่เราเติมเข้าไปเองจะถูกหนีซ้ำ
 * ใช้คู่กับ ESCAPE '\\' ใน SQL (ค่าปริยายของ Postgres เป็น \\ อยู่แล้ว จึงไม่ต้องเขียนเพิ่ม)
 */
export const likeEscape = (q) => String(q ?? '').replace(/[\\%_]/g, (ch) => `\\${ch}`);
