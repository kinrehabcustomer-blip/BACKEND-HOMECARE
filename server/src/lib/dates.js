/**
 * ตรวจว่า 'YYYY-MM-DD' เป็นวันที่ที่มีอยู่จริงในปฏิทิน
 *
 * เดิมทุกโมดูลตรวจด้วยรูปแบบอย่างเดียว (สี่หลัก-สองหลัก-สองหลัก) ซึ่งผ่านทั้ง 2026-02-31
 * และ 2026-13-45 · คอลัมน์วันที่ในฐานข้อมูลนี้เก็บเป็น TEXT ทั้งหมด (ดู schema.sql)
 * Postgres จึงไม่ได้ช่วยตรวจให้อีกชั้นเหมือนคอลัมน์ชนิด DATE — ของเสียลงฐานได้ตรงๆ
 * แล้วไปโผล่เป็นวันที่หายไปจากปฏิทิน/รายงาน หรือ new Date() ที่กลายเป็น Invalid Date บนหน้าเว็บ
 *
 * ตรวจด้วยการประกอบวันกลับมาเทียบ: 2026-02-31 จะถูก Date ปัดเป็น 2026-03-03 แล้วไม่ตรงกับต้นฉบับ
 */
export function isCalendarDate(value) {
  if (typeof value !== 'string') return false;
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(value);
  if (!m) return false;

  const [, y, mo, d] = m.map(Number);
  if (mo < 1 || mo > 12 || d < 1 || d > 31) return false;

  // ใช้ UTC ล้วน — เที่ยงคืนตามโซนเวลาเครื่องอาจถอยไปวันก่อนหน้าในบางโซน แล้วเทียบไม่ตรงทั้งที่วันถูก
  const dt = new Date(Date.UTC(y, mo - 1, d));
  return dt.getUTCFullYear() === y && dt.getUTCMonth() === mo - 1 && dt.getUTCDate() === d;
}

/** ข้อความเตือนชุดเดียวกันทุกโมดูล — คนกรอกเห็นคำอธิบายแบบเดียวกันไม่ว่าจะกรอกที่หน้าไหน */
export const DATE_MESSAGE = 'ต้องเป็นวันที่ที่มีอยู่จริงในรูปแบบ YYYY-MM-DD';

/**
 * ตัวตรวจวันที่สำหรับ zod — ใช้แทน z.string().regex(...) ที่กระจายอยู่ทุกโมดูล
 * รับ z เข้ามาเป็นพารามิเตอร์เพื่อให้ไฟล์นี้ไม่ต้องผูกกับเวอร์ชัน zod ของใคร
 */
export const zodDate = (z) => z.string().refine(isCalendarDate, DATE_MESSAGE);
